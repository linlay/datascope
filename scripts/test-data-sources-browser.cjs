  await manager.getByRole('cell', { name: 'CRM Reader', exact: true }).waitFor();
  await manager.getByRole('button', { name: /^关\s*闭$/ }).click();
  await manager.waitFor({ state: 'hidden' });
  assert.equal(await taskName.inputValue(), '客户导入');
  assert.equal(await taskId.inputValue(), 'customers');
  const selector = page.locator('.source-task-editor .ant-form-item').filter({ has: page.locator('label', { hasText: /^来源连接$/ }) }).locator('.ant-select');
  await selector.click(); await page.locator('.ant-select-dropdown:visible').getByText('CRM Reader (crm)', { exact: true }).click(); await page.keyboard.press('Escape');
  await page.locator('.source-task-editor .cm-content').first().fill('function main(params, context) { context.log("Import finished"); }');
