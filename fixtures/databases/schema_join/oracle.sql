-- Run as a fixture administrator in the target Service/PDB after provisioning
-- DS_SALES and DS_CRM owner users and the empty DS_JOIN_READER login. The reader
-- needs CREATE SESSION and the SELECT grants below, and owns no fixture tables.
CREATE TABLE DS_SALES.ORDERS(ORDER_ID NUMBER PRIMARY KEY,CUSTOMER_ID NUMBER,OWNER_ID NUMBER,SECRET VARCHAR2(50));
CREATE TABLE DS_CRM.CUSTOMERS(CUSTOMER_ID NUMBER PRIMARY KEY,CUSTOMER_NAME VARCHAR2(50),SECRET VARCHAR2(50));
CREATE TABLE DS_SALES.RECORDS(ID NUMBER PRIMARY KEY,OWNER_LABEL VARCHAR2(20));
CREATE TABLE DS_CRM.RECORDS(ID NUMBER PRIMARY KEY,OWNER_LABEL VARCHAR2(20));
INSERT INTO DS_SALES.ORDERS VALUES(1,7,1,'sales secret');
INSERT INTO DS_CRM.CUSTOMERS VALUES(7,'Alice','crm secret');
INSERT INTO DS_SALES.RECORDS VALUES(1,'DS_SALES');
INSERT INTO DS_CRM.RECORDS VALUES(1,'DS_CRM');
COMMENT ON TABLE DS_SALES.RECORDS IS 'First schema records';
COMMENT ON TABLE DS_CRM.RECORDS IS 'Second schema records';
GRANT SELECT ON DS_SALES.ORDERS TO DS_JOIN_READER;
GRANT SELECT ON DS_CRM.CUSTOMERS TO DS_JOIN_READER;
GRANT SELECT ON DS_SALES.RECORDS TO DS_JOIN_READER;
GRANT SELECT ON DS_CRM.RECORDS TO DS_JOIN_READER;
COMMIT;
